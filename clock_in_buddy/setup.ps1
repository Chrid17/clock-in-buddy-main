# Clock In Buddy 2.0 - one-time project setup (Windows PowerShell)
#
# Run from the clock_in_buddy folder:
#   powershell -ExecutionPolicy Bypass -File .\setup.ps1
#
# What it does:
#   1. Checks Flutter is 3.38.1 or newer (upgrades it if not).
#   2. Connects the app to your Supabase project using SUPABASE_URL and
#      SUPABASE_ANON_KEY from .env (the Odoo password is NOT copied into the app).
#   3. Removes the old version's code and recreates the android/ios/web folders.
#   4. Adds camera and location permissions for Android and iOS.
#   5. Generates app icons, then runs the analyzer and the tests.

$ErrorActionPreference = 'Stop'
Set-Location -Path $PSScriptRoot

function Step($text) { Write-Host ''; Write-Host "==> $text" -ForegroundColor Cyan }
function Info($text) { Write-Host "    $text" }
function Warn($text) { Write-Host "    $text" -ForegroundColor Yellow }
function Read-Text($path) { return [System.IO.File]::ReadAllText((Join-Path $PSScriptRoot $path)) }
function Write-Text($path, $content) {
    $enc = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText((Join-Path $PSScriptRoot $path), $content, $enc)
}
function Replace-InFile($path, $old, $new) {
    if (Test-Path $path) {
        $text = Read-Text $path
        if ($text.Contains($old)) { Write-Text $path ($text.Replace($old, $new)) }
    }
}
function Run($exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "'$exe $($arguments -join ' ')' failed (exit code $LASTEXITCODE)." }
}

if (-not (Test-Path 'lib\src\api\attendance_api.dart')) {
    throw 'Run this script from the clock_in_buddy folder.'
}

# ---------------------------------------------------------------------------
Step 'Checking Flutter'
$versionText = (& flutter --version | Out-String)
if ($versionText -match 'Flutter (\d+)\.(\d+)\.(\d+)') {
    $current = [version]("{0}.{1}.{2}" -f $Matches[1], $Matches[2], $Matches[3])
    Info "Found Flutter $current"
    if ($current -lt [version]'3.38.1') {
        Warn 'Clock In Buddy needs Flutter 3.38.1 or newer. Upgrading Flutter now...'
        Run 'flutter' @('upgrade')
    }
} else {
    throw 'Flutter was not found. Install it from https://docs.flutter.dev/get-started/install'
}

# ---------------------------------------------------------------------------
Step 'Connecting to your Supabase project'
$url = ''
$key = ''
if (Test-Path '.env') {
    foreach ($line in (Get-Content '.env')) {
        if ($line -match '^\s*SUPABASE_URL\s*=\s*(.+?)\s*$') { $url = $Matches[1].Trim('"', "'") }
        if ($line -match '^\s*SUPABASE_(ANON|PUBLISHABLE)_KEY\s*=\s*(.+?)\s*$') { $key = $Matches[2].Trim('"', "'") }
    }
}
if ($url -and $key) {
    $envDart = @"
// Generated by setup.ps1 from .env.
//
// The publishable (anon) key is designed to be public: it is in every
// Supabase web and mobile app. Your data is protected by the Row Level
// Security rules in supabase/migrations, not by hiding this key.
// Never put the service_role key or the Odoo password here.
const String supabaseUrl = '$url';
const String supabaseKey = '$key';
"@
    Write-Text 'lib\src\env.dart' $envDart
    Info "Using $url"
} else {
    Warn 'SUPABASE_URL / SUPABASE_ANON_KEY not found in .env. Fill in lib\src\env.dart yourself.'
}

# ---------------------------------------------------------------------------
Step 'Removing the old version'
$old = @(
    'lib\config', 'lib\models', 'lib\screens', 'lib\services',
    'test\widget_test.dart', 'analysis_report.txt', 'analysis_result.txt',
    'android', 'ios', 'web', 'windows', 'linux', 'macos',
    'pubspec.lock', 'build', '.dart_tool', '.flutter-plugins', '.flutter-plugins-dependencies'
)
foreach ($p in $old) {
    if (Test-Path $p) {
        try {
            Remove-Item $p -Recurse -Force
            Info "removed $p"
        } catch {
            throw "Could not delete '$p'. Close Android Studio, emulators and any running app, then run this again. ($($_.Exception.Message))"
        }
    }
}

# ---------------------------------------------------------------------------
Step 'Creating the Android, iOS and web projects'
Run 'flutter' @('create', '--org', 'com.chrisbwendo', '--project-name', 'clock_in_buddy',
    '--platforms=android,ios,web', '.')
if (Test-Path 'test\widget_test.dart') { Remove-Item 'test\widget_test.dart' -Force }

# ---------------------------------------------------------------------------
Step 'Adding camera and location permissions'
$manifest = 'android\app\src\main\AndroidManifest.xml'
$m = Read-Text $manifest
if (-not $m.Contains('android.permission.CAMERA')) {
    $permissions = @"

    <uses-permission android:name="android.permission.INTERNET"/>
    <uses-permission android:name="android.permission.CAMERA"/>
    <uses-permission android:name="android.permission.ACCESS_FINE_LOCATION"/>
    <uses-permission android:name="android.permission.ACCESS_COARSE_LOCATION"/>
    <uses-feature android:name="android.hardware.camera" android:required="false"/>
    <uses-feature android:name="android.hardware.location.gps" android:required="false"/>
"@
    $re = New-Object System.Text.RegularExpressions.Regex('(<manifest[^>]*>)')
    $m = $re.Replace($m, '$1' + $permissions, 1)
}
$m = $m.Replace('android:label="clock_in_buddy"', 'android:label="Clock In Buddy"')
Write-Text $manifest $m
Info 'Android: internet, camera and location'

$plist = 'ios\Runner\Info.plist'
$p = Read-Text $plist
if (-not $p.Contains('NSCameraUsageDescription')) {
    $keys = @"
	<key>NSCameraUsageDescription</key>
	<string>Clock In Buddy takes a selfie when you clock in or out, as proof of attendance.</string>
	<key>NSMicrophoneUsageDescription</key>
	<string>The camera needs this permission on some devices. Clock In Buddy never records audio.</string>
	<key>NSLocationWhenInUseUsageDescription</key>
	<string>Clock In Buddy records your location when you clock in or out, as proof of where you worked.</string>
"@
    $idx = $p.LastIndexOf('</dict>')
    $p = $p.Substring(0, $idx) + $keys + "`n" + $p.Substring($idx)
}
$p = $p.Replace('<string>clock_in_buddy</string>', '<string>Clock In Buddy</string>')
Write-Text $plist $p
Info 'iOS: camera and location descriptions'

Replace-InFile 'web\index.html' '<title>clock_in_buddy</title>' '<title>Clock In Buddy</title>'
Replace-InFile 'web\index.html' 'content="clock_in_buddy"' 'content="Clock In Buddy"'
Replace-InFile 'web\manifest.json' '"name": "clock_in_buddy"' '"name": "Clock In Buddy"'
Replace-InFile 'web\manifest.json' '"short_name": "clock_in_buddy"' '"short_name": "Clock In"'

# ---------------------------------------------------------------------------
Step 'Getting packages'
Run 'flutter' @('pub', 'get')

Step 'Generating app icons'
try { Run 'dart' @('run', 'flutter_launcher_icons') } catch { Warn "Icons skipped: $($_.Exception.Message)" }

Step 'Checking the code'
$problems = $false
try { Run 'flutter' @('analyze', '--no-fatal-infos') } catch { $problems = $true; Warn $_.Exception.Message }
try { Run 'flutter' @('test') } catch { $problems = $true; Warn $_.Exception.Message }
if ($problems) { Warn 'Some checks reported problems (see above). Copy the output and send it to Claude.' }

Write-Host ''
Write-Host 'All done! Next steps:' -ForegroundColor Green
Write-Host '  1. Supabase Dashboard > SQL Editor: run supabase\migrations\20261102000000_remote_clock_in.sql'
Write-Host '  2. Run on a phone:  flutter run        (or in Chrome: flutter run -d chrome)'
Write-Host '  3. Optional Odoo sync: see README.md'
